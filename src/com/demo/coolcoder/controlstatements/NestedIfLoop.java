package com.demo.coolcoder.controlstatements;

public class NestedIfLoop {
	
	public static void main(String[] args) {
		
		int a = 10;
		
		int  b = 20;
		
		int inputNumber = 8;
		
		if (inputNumber < a) {
			System.out.println("inputNumber less than a");
		}
		
		if (inputNumber < b) {
			System.out.println("inputNumber less than b");
		}
		
		
	}

	

}
