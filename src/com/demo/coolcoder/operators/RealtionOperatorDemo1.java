package com.demo.coolcoder.operators;

public class RealtionOperatorDemo1 {
	
	public static void main(String[] args) {
		
		
		int a = 30;
		int b = 40;
		
		//compare the data
		
		//relation operator produce result as boolean(true,false)
		
		System.out.println(a == b);
		
		System.out.println(a<b);
		
		System.out.println(a<=b);
		
		System.out.println(a>b);
		
		System.out.println(a>=b);
		
		System.out.println(a != b);
	}

}
